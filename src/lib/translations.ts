export function getCategoryTitle(catName: string, lang: Language): string {
  if (lang === 'tr') return catName;
  const key = catName.trim().toLowerCase();
  const match = categoryTranslations[key];
  if (match && match[lang]) {
    return match[lang];
  }
  return catName;
}
